import { existsSync, readFileSync } from 'node:fs';
import { PublicConfig } from 'common';
import * as YAML from 'yaml';
import { z } from 'zod';

const publicConfigFileName = 'config.public.yaml';

const publicConfigPath = `../${publicConfigFileName}`;

const readPublicConfig = (): unknown => {
    if (!existsSync(publicConfigPath)) {
        throw new Error(
            `Missing ${publicConfigFileName} at the root: copy and edit config.public.example.yaml to start`,
        );
    }
    return YAML.parse(readFileSync(publicConfigPath, 'utf8'));
};

const GeocoderProviderNameSchema = z.enum(['pelias']);

// From .env, under the names of its variables
const PrivateConfigSchema = z
    .object({
        BACKEND_PORT: z.coerce.number().int().positive(),
        GEOCODER_PROVIDER: GeocoderProviderNameSchema,
        GEOCODER_URL: z.url(),
        TRANSITION_USER_NAME: z.string().min(1),
        TRANSITION_USER_PASSWORD: z.string().min(1),
        // Used only by the client generated by Orval
        // Required for the backend to work
        TRANSITION_URL: z.url(),
    })
    .transform((env) => ({
        port: env.BACKEND_PORT,
        geocoder: {
            provider: env.GEOCODER_PROVIDER,
            url: env.GEOCODER_URL,
        },
        transition: {
            userName: env.TRANSITION_USER_NAME,
            password: env.TRANSITION_USER_PASSWORD,
        },
    }));

export type PrivateConfig = z.output<typeof PrivateConfigSchema>;

const parsePrivateConfig = () => {
    const result = PrivateConfigSchema.safeParse(process.env);
    if (!result.success) {
        throw new Error(
            `Invalid .env, see .env.example:\n${z.prettifyError(result.error)}`,
        );
    }
    return result.data;
};

export const readConfig = () => {
    return {
        public: PublicConfig.RefinedPublicConfigSchema.parse(
            readPublicConfig(),
        ),
        private: parsePrivateConfig(),
    };
};
